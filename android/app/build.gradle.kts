import java.util.Properties
import java.io.FileInputStream

plugins {
    id("com.android.application")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

// A debug build must not require release credentials. A release must have a
// complete upload-key configuration; never silently fall back to debug signing.
val releaseRequested = gradle.startParameter.taskNames.any {
    it.contains("release", ignoreCase = true)
}
if (releaseRequested) {
    val requiredKeys = listOf("storeFile", "storePassword", "keyAlias", "keyPassword")
    val missingKeys = requiredKeys.filter { keystoreProperties.getProperty(it).isNullOrBlank() }
    if (missingKeys.isNotEmpty()) {
        throw GradleException(
            "Release signing is not configured (${missingKeys.joinToString()}). " +
                "Run: bash tools/release/setup_upload_key.sh"
        )
    }
    val signingStore = file(keystoreProperties.getProperty("storeFile"))
    if (!signingStore.isFile) {
        throw GradleException("Release upload keystore not found: $signingStore")
    }
}

